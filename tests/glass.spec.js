import { test, expect } from '@playwright/test'

test('glass decoration preserves native keyboard navigation, search and dialogs', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.hero-feature.liquid-glass-ready')).toBeVisible()
  await expect(page.locator('.desktop-nav .liquid-glass-layer')).toHaveCount(1)
  await expect(page.locator('.liquid-glass-layer a,.liquid-glass-layer button,.liquid-glass-layer input')).toHaveCount(0)
  await page.locator('.hero-feature').focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/title\/\d+$/)
  await expect(page.locator('main')).not.toHaveAttribute('aria-busy', 'true')
  await expect(page.locator('.hero-feature')).toHaveCount(0)
  await page.locator('.desktop-nav a[data-nav=catalog]').click()
  await expect(page.locator('.title-card').first()).toBeVisible()
  await page.keyboard.press('/')
  await expect(page.locator('#search')).toBeFocused()
  await page.locator('#search').fill('Интерстеллар')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Поиск: «Интерстеллар»' })).toBeVisible()
  await expect(page.locator('.desktop-nav .liquid-glass-layer')).toHaveCount(1)
  await page.getByRole('button', { name: /^Войти/ }).click()
  await expect(page.locator('#modal')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#modal')).not.toBeVisible()
  expect(errors).toEqual([])
})

test('glass dock survives viewport changes, language changes and reduced motion', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width:390, height:844 })
  await page.goto('/')
  const dock = page.locator('.mobile-nav')
  await expect(dock.locator('.liquid-glass-layer .glass')).toBeVisible()
  await dock.getByRole('link', { name:'Каталог', exact:true }).click()
  await expect(page.locator('.title-card').first()).toBeVisible()
  await page.locator('#language-switch').click()
  await expect(dock.locator('[aria-current=page]')).toHaveText('Catalog')
  for (const width of [320, 390, 768, 950, 1440]) {
    await page.setViewportSize({ width, height:844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width <= 760) await expect(dock.locator('.liquid-glass-layer .glass')).toBeVisible()
    else await expect(page.locator('.desktop-nav .liquid-glass-layer .glass')).toBeVisible()
  }
  await page.emulateMedia({ reducedMotion:'reduce' })
  await page.setViewportSize({ width:390, height:844 })
  await dock.getByRole('link', { name:'Overview', exact:true }).click()
  await expect(page.locator('.hero-feature.liquid-glass-ready')).toBeVisible()
  expect(await page.evaluate(() => document.getAnimations().some(animation => animation.playState === 'running' && animation.effect.getTiming().duration > 1))).toBe(false)
  expect(errors).toEqual([])
})

test('navigation and search remain usable when the optional glass module fails', async ({ page }) => {
  await page.route('**/assets/liquid-glass.js', route => route.abort())
  await page.goto('/')
  await expect(page.locator('.hero-feature')).toBeVisible()
  await page.locator('.desktop-nav a[data-nav=catalog]').click()
  await expect(page.locator('.title-card').first()).toBeVisible()
  await page.locator('#search').fill('Интерстеллар')
  await page.locator('#search').press('Enter')
  await expect(page.getByRole('heading', { name:'Поиск: «Интерстеллар»' })).toBeVisible()
  await expect(page.locator('.liquid-glass-ready')).toHaveCount(0)
})

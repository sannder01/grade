test('Grade uses its own database schema and leaves another application intact',async()=>{
  const {default:pg}=await import('pg')
  const client=new pg.Client({connectionString:process.env.DATABASE_URL,ssl:false})
  await client.connect()
  try {
    const other=await client.query('SELECT * FROM public."user"')
    expect(other.rows).toEqual([{id:'other-app',marker:'untouched'}])
    expect((await client.query("SELECT to_regclass('grade_ci.user') IS NOT NULL AS present")).rows[0].present).toBe(true)
    expect((await client.query("SELECT to_regclass('public.titles') AS name")).rows[0].name).toBeNull()
  }finally{await client.end()}
})
async function register(playwright, prefix='viewer', clientIp=null) {
  const username=prefix+stamp()
  const api=await playwright.request.newContext({baseURL,extraHTTPHeaders:{Origin:baseURL,...(clientIp?{'X-Forwarded-For':clientIp}:{})}})
  const response=await api.post('/api/auth/sign-up/email',{data:{name:'Зритель '+prefix,email:username+'@example.test',password,username}})
  expect(response.status(),await response.text()).toBe(200)
  const me=await (await api.get('/api/me')).json()
  expect(me.user.username).toBe(username)
  return {api,username,me}
}
async function call(api,path,method='GET',data,status=200) {
  const response=await api.fetch(path,{method,...(data===undefined?{}:{data})})
  expect(response.status(),`${method} ${path}: ${await response.text()}`).toBe(status)
  return response.json()
}


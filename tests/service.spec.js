test('public profiles, independent collections and real aggregate scores persist',async({playwright,request})=>{
  const a=await register(playwright,'alice'),b=await register(playwright,'blair')
  const titles=(await call(a.api,'/api/catalog')).items
  expect(titles.length).toBeGreaterThanOrEqual(20)
  const first=titles[0].id,second=titles[1].id
  await call(a.api,`/api/titles/${first}/watched`,'PUT',{watched:true,user_id:b.me.user.id})
  let profile=await call(a.api,`/api/profiles/${a.username}?tab=watched`)
  expect(profile.stats.watched).toBe(1);expect(profile.stats.rated).toBe(0)
  expect(profile.items[0].my_score).toBeNull()
  expect((await call(b.api,`/api/profiles/${b.username}`)).stats.watched).toBe(0)
  await call(a.api,`/api/titles/${first}/rating`,'PUT',{score:8})
  await call(a.api,`/api/titles/${second}/rating`,'PUT',{score:9})
  await call(a.api,`/api/titles/${first}/watched`,'PUT',{watched:false})
  profile=await call(a.api,`/api/profiles/${a.username}?tab=ratings`)
  expect(profile.stats.watched).toBe(0);expect(profile.stats.rated).toBe(2)
  expect(profile.items.find((row)=>row.id===second).watched).toBe(false)
  const publicProfile=await call(b.api,`/api/profiles/${a.username}`)
  expect(JSON.stringify(publicProfile)).not.toContain('@example.test')
  expect(publicProfile.own).toBe(false)
  await call(b.api,`/api/titles/${first}/rating`,'PUT',{score:6})
  await call(b.api,`/api/titles/${first}/rating`,'PUT',{score:6})
  const item=await call(b.api,`/api/titles/${first}`)
  expect(item.votes).toBe(2);expect(item.average).toBe(7)
  await call(a.api,`/api/titles/${first}/rating`,'DELETE')
  expect((await call(a.api,`/api/profiles/${a.username}`)).stats.rated).toBe(1)
  expect((await request.put(`/api/titles/${first}/rating`,{headers:{Origin:baseURL},data:{score:1}})).status()).toBe(401)
  await call(a.api,`/api/titles/${first}/rating`,'PUT',{score:11},400)
  expect((await a.api.put(`/api/titles/${first}/watched`,{headers:{Origin:'https://evil.test'},data:{watched:true}})).status()).toBe(403)
  expect((await a.api.put(`/api/titles/${first}/watched`,{data:{watched:'true'}})).status()).toBe(400)
  await call(a.api,'/api/auth/sign-out','POST',{})
  expect((await call(a.api,'/api/me')).user).toBeNull()
  await call(a.api,'/api/auth/sign-in/username','POST',{username:a.username,password})
  expect((await call(a.api,'/api/me')).user.username).toBe(a.username)
  expect((await call(a.api,`/api/profiles/${a.username}`)).stats.rated).toBe(1)
  await a.api.dispose();await b.api.dispose()
})

test('spoilers are redacted, clean filters exclude replies and only owners can remove posts',async({playwright})=>{
  const a=await register(playwright,'writer'),b=await register(playwright,'reader')
  const title=(await call(a.api,'/api/catalog')).items[3].id
  const secret='SECRET ENDING '+stamp()
  const parent=await call(a.api,`/api/titles/${title}/comments`,'POST',{content:secret,spoiler:true},201)
  const reply=await call(b.api,`/api/titles/${title}/comments`,'POST',{content:'HIDDEN REPLY',parent_id:parent.id,spoiler:false},201)
  const list=await call(b.api,`/api/titles/${title}/discussion?type=comments`)
  expect(JSON.stringify(list)).not.toContain(secret)
  expect(list.items.find((row)=>row.id===parent.id).content).toBeNull()
  expect(list.items.find((row)=>row.id===reply.id).spoiler).toBe(true)
  const clean=await call(b.api,`/api/titles/${title}/discussion?type=comments&filter=clean`)
  expect(clean.items.some((row)=>row.id===parent.id||row.id===reply.id)).toBe(false)
  expect((await call(b.api,`/api/comments/${parent.id}/reveal`)).content).toBe(secret)
  await call(b.api,`/api/comments/${parent.id}`,'DELETE',undefined,404)
  const review=await call(a.api,`/api/titles/${title}/review`,'PUT',{content:'A review with a secret ending: '+secret,spoiler:true})
  expect(JSON.stringify(await call(b.api,`/api/titles/${title}/discussion?type=reviews`))).not.toContain(secret)
  expect((await call(a.api,`/api/titles/${title}/my-review`)).id).toBe(review.id)
  await call(b.api,`/api/reviews/${review.id}`,'DELETE',undefined,404)
  await call(a.api,`/api/titles/${title}/review`,'PUT',{content:'A thoughtful spoiler-free review of the atmosphere.',spoiler:false})
  expect((await call(a.api,`/api/titles/${title}/discussion?type=reviews`)).total).toBe(1)
  await call(a.api,`/api/comments/${parent.id}`,'DELETE')
  await call(b.api,`/api/comments/${reply.id}/reveal`,'GET',undefined,404)
  await a.api.dispose();await b.api.dispose()
})


import { test, expect } from '@playwright/test'
test.use({locale:'ru-RU'})
const ready = page => expect(page.locator('main')).not.toHaveAttribute('aria-busy','true')

test('track frame follows routes and retains a readable selection without motion', async ({page}) => {
  const errors=[]; page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await ready(page)
  await expect(page.locator('.brand-caption')).toHaveCount(0)
  await expect(page.locator('.track-header .brand use')).toHaveAttribute('href','/icons.svg#brand')
  for (const section of ['collections','catalog','home']) {
    await page.locator(`.desktop-nav a[data-nav=${section}]`).click()
    await ready(page)
    await expect(page.locator(`.desktop-nav a[data-nav=${section}]`)).toHaveAttribute('aria-current','page')
    await expect.poll(async()=>{
      const frame=await page.locator('.desktop-nav .nav-indicator').boundingBox()
      const link=await page.locator('.desktop-nav a.active').boundingBox()
      return frame && link ? Math.abs(frame.x-link.x)+Math.abs(frame.y-link.y)+Math.abs(frame.width-link.width)+Math.abs(frame.height-link.height) : 100
    }).toBeLessThan(2)
  }
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.locator('.desktop-nav a[data-nav=collections]').click()
  await ready(page)
  await expect(page.locator('.desktop-nav a.active .track-label')).toHaveText('Подборки')
  expect(errors).toEqual([])
})


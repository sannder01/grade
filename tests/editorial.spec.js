test('black theme and every main page fit 320, 390, 768 and 1440 px', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  for (const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:844})
    for (const path of ['/','/collections','/collections/other-worlds','/catalog?view=grade','/title/1','/me','/about']) {
      await page.goto(path)
      await ready(page)
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await expect(page.locator('body')).toHaveCSS('background-color','rgb(9, 9, 11)')
    }
    if (width <= 760) await expect(page.locator('.section-toggle')).toBeVisible()
    else await expect(page.locator('.section-toggle')).not.toBeVisible()
  }
  expect(errors).toEqual([])
})


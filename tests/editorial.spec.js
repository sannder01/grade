test('reduced motion disables travel and stagger but keeps all controls and dialogs', async ({ page }) => {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/')
  await ready(page)
  await expect(page.locator('[data-reveal]')).toHaveCount(0)
  await page.locator('.collection-card').first().click()
  await ready(page)
  await expect(page.locator('.flying-poster')).toHaveCount(0)
  await expect(page.locator('.title-card').first()).toBeVisible()
  await page.locator('.poster-link').first().click()
  await ready(page)
  await page.locator('.rating-scale button').first().click()
  await expect(page.locator('#modal')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#modal')).not.toBeVisible()
  expect(await page.evaluate(async () => {
    const {gsap} = await import('/assets/motion-vendor.js')
    return gsap.globalTimeline.getChildren(true,true,true).filter(tween => tween.isActive() && tween.duration() > .01).length
  })).toBe(0)
})

test('touch exposes card actions and vertical dragging preserves native scrolling', async ({ browser, browserName }) => {
  test.skip(browserName !== 'chromium', 'CDP native touch injection is Chromium-specific')
  const context = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  try {
    const page = await context.newPage()
    await page.goto('http://127.0.0.1:3100/catalog?view=grade')
    await ready(page)
    await expect(page.locator('.card-actions').first()).toHaveCSS('opacity','1')
    await page.locator('.card-plan').first().tap()
    await expect(page.locator('#modal')).toBeVisible()
    await page.locator('.modal-close').tap()
    await expect(page.locator('#modal')).not.toBeVisible()
    const cdp = await context.newCDPSession(page)
    const touch = (type,x,y) => cdp.send('Input.dispatchTouchEvent',{type,touchPoints:type === 'touchEnd' ? [] : [{x,y}]})
    await touch('touchStart',190,650)
    for (let step=1;step<=10;step++) await touch('touchMove',190,650-step*25)
    await touch('touchEnd',190,400)
    await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(100)
    await expect(page.locator('#modal')).not.toBeVisible()
    await expect(page).toHaveURL(/\/catalog\?view=grade$/)
  } finally { await context.close() }
})

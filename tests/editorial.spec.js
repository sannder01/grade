import { test, expect } from '@playwright/test'
test.use({locale:'ru-RU'})

const ready = page => expect(page.locator('main')).not.toHaveAttribute('aria-busy','true')
const settled = page => expect(page.locator('.flying-poster')).toHaveCount(0)

test('collection cover unfolds, a poster opens its title, and Back restores the same view', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await ready(page)
  await expect(page.locator('.collection-card')).toHaveCount(3)
  const cover = page.locator('.collection-card').first()
  const name = await cover.locator('h3').innerText()
  await cover.click()
  await ready(page)
  await expect(page.locator('h1')).toHaveText(name)
  await expect(page.locator('.title-card').first()).toBeVisible()
  await settled(page)
  const card = page.locator('.poster-link').last()
  await card.scrollIntoViewIfNeeded()
  await card.focus()
  const href = await card.getAttribute('href')
  const before = await page.evaluate(() => scrollY)
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(new RegExp(`${href}$`))
  await ready(page)
  await expect(page.locator('.detail-poster')).toBeVisible()
  await settled(page)
  await page.locator('.back-link').click()
  await ready(page)
  await settled(page)
  await expect(page.locator('h1')).toHaveText(name)
  expect(Math.abs(await page.evaluate(() => scrollY)-before)).toBeLessThan(3)
  await expect(page.locator(`.poster-link[href="${href}"]`)).toBeFocused()
  expect(errors).toEqual([])
})

test('collection sorting animates card positions and repeated filters keep the latest state', async ({ page }) => {
  await page.goto('/collections/other-worlds')
  await ready(page)
  await page.locator('#collection-sort').selectOption('new')
  await ready(page)
  const years = await page.locator('.card-meta>span:first-child').allTextContents()
  const values = years.map(value => parseInt(value))
  expect(values).toEqual([...values].sort((a,b) => b-a))
  await page.locator('#collection-sort').selectOption('rating')
  await page.locator('#collection-sort').selectOption('popular')
  await ready(page)
  await expect(page.locator('#collection-sort')).toHaveValue('popular')
  await page.locator('.category-pills a').filter({hasText:'Сериалы'}).click()
  await ready(page)
  await expect(page.locator('.card-meta')).not.toHaveCount(0)
  for (const value of await page.locator('.card-meta').allTextContents()) expect(value).toContain('Сериал')
  await expect(page.locator('.category-pills a.active')).toHaveText('Сериалы')
  await expect.poll(() => page.locator('.title-card').evaluateAll(nodes => nodes.every(node => getComputedStyle(node).position !== 'absolute'))).toBe(true)
})


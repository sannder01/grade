export function errorMessage(message, code, status) {
  const value = authErrors[code] || (typeof message === 'string' ? message : 'Не удалось выполнить запрос')
  if (status === 429) return t('Слишком много действий. Подождите минуту.')
  const translated = t(value)
  if (current === 'en' && /[А-Яа-яЁё]/.test(translated)) return 'Check your details and try again'
  return translated
}
